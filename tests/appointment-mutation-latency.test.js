const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const { Readable } = require('node:stream');
const { performance } = require('node:perf_hooks');
const { ObjectId } = require('mongodb');
const jwt = require('jsonwebtoken');
const { memoryDb } = require('./helpers/memory-db');

async function main() {
  let sends = 0;
  const notificationRequire = require('node:module').createRequire(path.resolve('lib/notifications.js'));
  const messagingContext = { require: name => name === './account-security' ? { sendEmail: async () => { sends++; return 'mock-id'; } } : notificationRequire(name), module: { exports: {} }, process: { env: { SMS_ROUTINE_UPDATES: 'false' } }, AbortSignal, Buffer, URLSearchParams };
  vm.runInNewContext(fs.readFileSync('lib/notifications.js', 'utf8'), messagingContext);
  const messaging = messagingContext.module.exports;
  const admin = { _id: new ObjectId(), role: 'admin' };
  const user = { _id: new ObjectId(), email: 'isolated@example.test', emailVerifiedAt: new Date() };
  const appointment = { _id: new ObjectId(), userId: user._id, status: 'pending', date: '2099-01-05', time: '14:00', serviceId: 'cut', barberId: 'alex', total: 250, bookingFee: 100, servicePaymentMethod: 'cash', durationMinutes: 30 };
  const unrelated = { ...appointment, _id: new ObjectId(), date: '2000-01-01' };
  const database = memoryDb({ users: [admin, user], appointments: [appointment, unrelated], services: [{ _id: new ObjectId(), slug: 'cut', active: true, duration: '30 min' }], barbers: [{ _id: new ObjectId(), slug: 'alex', status: 'active' }], settings: [{ _id: 'shop' }] });
  const localRequire = require('node:module').createRequire(path.resolve('api/index.js'));
  const context = { require: name => name === '../lib/notifications' ? messaging : localRequire(name), module: { exports: {} }, URL, console, process: { env: { JWT_SECRET: 'latency-test' } }, database };
  vm.runInNewContext(`${fs.readFileSync('api/index.js', 'utf8')}\ndb = async () => database;`, context);
  async function request(body, url = `/api/admin/appointments/${appointment._id}`) {
    const req = Readable.from([JSON.stringify(body)]);
    Object.assign(req, { method: 'PATCH', url, headers: { authorization: `Bearer ${jwt.sign({ sub: String(admin._id) }, 'latency-test')}` } });
    let result;
    const res = { setHeader() {}, end(raw) { result = JSON.parse(raw); } };
    const start = performance.now();
    await context.module.exports(req, res);
    return { status: res.statusCode, data: result, ms: performance.now() - start };
  }
  const accepted = await request({ status: 'confirmed' });
  assert.equal(accepted.status, 200, JSON.stringify(accepted.data));
  assert.equal(accepted.data.appointment.status, 'confirmed');
  assert.equal(appointment.bookingFeePaid, true);
  assert.equal(appointment.servicePaid, false);
  assert.equal(sends, 0, 'Mutation never enters email/SMS delivery');
  assert.equal(database.records.notifications.length, 1, 'Bell entry exists before PATCH returns');
  assert.equal(unrelated.status, 'pending', 'No global cleanup on mutation');
  unrelated.date = appointment.date;
  assert.equal(Object.keys(appointment.notificationOutbox).length, 1);
  assert.equal((await request({ status: 'completed' })).status, 409, 'Cannot complete before serving');
  const ticketId = new ObjectId();
  await database.collection('queue').insertOne({ _id: ticketId, userId: user._id, appointmentId: String(appointment._id), status: 'waiting', source: 'appointment', barberId: 'alex', scheduledAt: new Date(0), createdAt: new Date() });
  assert.equal((await request({ status: 'serving' }, `/api/admin/queue/${ticketId}`)).status, 200);
  assert.equal(database.records.notifications.length, 2, 'Serving bell entry is immediate');
  assert.equal(sends, 0, 'Queue serving does not enter provider delivery');
  assert.equal((await request({ status: 'completed' })).status, 400, 'Exact cash collection still required');
  assert.equal((await request({ status: 'completed', cashCollected: true, cashAmount: 150 })).status, 200);
  assert.equal(appointment.paid, true);
  assert.equal(database.records.queue[0].status, 'done');
  assert.equal(sends, 0);
  await require('../lib/notification-outbox').flush(database, messaging.notify);
  assert.equal(sends, 0, 'Outbox flush only persists, never delivers');
  assert.equal(database.records.notifications.length, 3, 'Immediate and outbox entries deduplicate');
  await context.module.exports.sweepNotifications();
  assert.equal(sends, 3, 'Worker later delivers persisted notices using mock email');
  await context.module.exports.sweepNotifications();
  assert.equal(sends, 3, 'Delivery is deduplicated');
  await messaging.notify(database, user._id, 'Deferred notification', 'deferred-test', { enqueueOnly: true });
  assert.equal(sends, 3);
  await messaging.retryPending(database);
  assert.equal(sends, 4, 'Deferred records remain eligible for delivery');
  const cancelledId = new ObjectId();
  await database.collection('queue').insertOne({ _id: cancelledId, userId: user._id, appointmentId: String(unrelated._id), status: 'waiting', source: 'appointment', createdAt: new Date() });
  assert.equal((await request({ status: 'cancelled' }, `/api/admin/queue/${cancelledId}`)).status, 200);
  assert.equal(sends, 4, 'Queue cancellation is persistence-only too');
  assert.ok(database.records.notifications.some(record => record.queueTicketId?.equals(cancelledId)));

  const outbox = require('../lib/notification-outbox');
  const backlog = memoryDb({ users: [user], appointments: Array.from({ length: 40 }, (_, i) => ({ _id: new ObjectId(), notificationOutbox: { event: { userId: user._id, message: `Backlog ${i}`, key: `backlog:${i}` } } })) });
  await assert.rejects(outbox.flush(backlog, async () => { throw new Error('Insert unavailable'); }), /Insert unavailable/);
  assert.ok(backlog.records.appointments[0].notificationOutbox.event, 'Persistence failure retains recovery event');
  await outbox.flush(backlog, messaging.notify);
  assert.equal(backlog.records.notifications.length, 40, 'Entire backlog is bell-visible before any provider call');
  assert.equal(sends, 4);
  await messaging.retryPending(backlog);
  assert.equal(sends, 29, 'Delivery batch remains bounded at 25 without delaying bell persistence');
  assert.equal(backlog.records.notifications.length, 40);
  let smsCalls = 0;
  const consentContext = { ...messagingContext, module: { exports: {} }, process: { env: { SMS_PROVIDER: 'iprog', IPROG_API_TOKEN: 'isolated-fake-token' } }, globalThis: { fetch: async () => { smsCalls++; throw new Error('No network allowed'); } } };
  vm.runInNewContext(fs.readFileSync('lib/notifications.js', 'utf8'), consentContext);
  const noConsent = { _id: new ObjectId(), phone: '09171234567', phoneVerifiedAt: new Date(), smsConsent: false };
  const unverified = { _id: new ObjectId(), phone: '09171234568', smsConsent: true };
  const consentDb = memoryDb({ users: [noConsent, unverified] });
  for (const user of [noConsent, unverified]) await consentContext.module.exports.notify(consentDb, user._id, 'Consent guard test', `consent:${user._id}`, { enqueueOnly: true });
  await consentContext.module.exports.retryPending(consentDb);
  assert.equal(smsCalls, 0, 'No SMS without both verified phone and consent, even with a configured provider');
  assert.ok(consentDb.records.notifications.every(record => record.channels.sms.status === 'not-enabled'));
  console.log(`Acceptance PATCH: ${accepted.ms.toFixed(1)}ms (isolated memory DB); no provider calls, durable outbox, later delivery, serving-only completion and exact cash validation passed.`);
}
main().catch(error => { console.error(error); process.exitCode = 1; });
