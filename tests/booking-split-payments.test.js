const assert = require('node:assert/strict');
const { paymentChoice, bookingPaymentChoice, paymentUpdate, paymentCollections, cashBalance } = require('../lib/booking-payments');
const { buildAnalytics, buildBarberPerformance } = require('../lib/analytics');
const feeDate = new Date('2026-11-15T02:00:00Z');
const cashDate = new Date('2026-11-16T02:00:00Z');
const pending = { _id: 'booking', barberId: 'alex', servicePaymentMethod: 'cash', bookingFee: 100, total: 350, paid: false, bookingFeePaid: false, servicePaid: false, createdAt: feeDate };
assert.equal(paymentChoice(), 'online');
assert.equal(paymentChoice('cash'), 'cash');
assert.equal(bookingPaymentChoice('onsite'), 'onsite');
assert.equal(bookingPaymentChoice('online'), 'online');
assert.throws(() => bookingPaymentChoice('later'), { status: 400 });
for (const value of ['Cash', '', null, false, 'GCash']) assert.throws(() => paymentChoice(value), { status: 400 });
assert.deepEqual(paymentCollections(pending, 350), []);
const approved = { ...pending, ...paymentUpdate(pending, 'confirmed', feeDate) };
assert.equal(approved.paid, false);
assert.equal(approved.servicePaid, false);
assert.deepEqual(paymentCollections(approved, 350), [{ component: 'reservation-fee', tender: 'online', amount: 100, paidAt: feeDate }]);
const report = item => buildAnalytics([item], [], 1, [], cashDate);
assert.equal(report(approved).totals.revenue, 100);
assert.equal(report({ ...approved, paid: true }).totals.revenue, 100, 'Generic paid flag must not count uncollected cash');
assert.equal(buildBarberPerformance([approved], [], [], [])[0].revenue, 100);
for (const status of ['cancelled', 'disapproved']) assert.deepEqual(paymentUpdate(approved, status, cashDate), {});
for (const confirmation of [{}, { cashAmount: 250 }, { cashCollected: true }, { cashCollected: true, cashAmount: 249 }, { cashCollected: true, cashAmount: '250' }, { cashCollected: true, cashAmount: NaN }]) assert.throws(() => paymentUpdate(approved, 'completed', cashDate, confirmation), { status: 400 });
const confirmation = { cashCollected: true, cashAmount: 250 };
const completed = { ...approved, ...paymentUpdate(approved, 'completed', cashDate, confirmation) };
assert.equal(completed.paid, true);
assert.equal(report(completed).totals.revenue, 350);
assert.equal(report(completed).daily.find(day => day.date === '2026-11-15').revenue, 100);
assert.equal(report(completed).daily.find(day => day.date === '2026-11-16').revenue, 250);
assert.equal(report(completed).collections.bookings, 350);
assert.deepEqual(report(completed).collections.records.map(item => [item.id, item.source, item.component, item.tender]).sort(), [['booking:reservation-fee', 'booking', 'reservation-fee', 'online'], ['booking:service', 'booking', 'service', 'cash']]);
assert.equal(new Set(report(completed).collections.records.map(item => item.id)).size, 2);
for (const cancelledBy of ['customer', 'no-show']) assert.equal(report({ ...approved, status: 'cancelled', cancelledBy }).totals.revenue, 100);
assert.deepEqual(paymentUpdate(completed, 'completed', new Date()), paymentUpdate(completed, 'completed', cashDate), 'Repeated completion preserves payment timestamps');
assert.equal(buildBarberPerformance([completed], [], [], [])[0].revenue, 350);
const onsite = { ...pending, bookingPaymentMethod: 'onsite', servicePaymentMethod: 'cash', bookingFeePaid: false, servicePaid: false, paid: false };
assert.equal(cashBalance(onsite), 350, 'Entire onsite total remains due until collected');
assert.deepEqual(paymentUpdate(onsite, 'confirmed', feeDate), {}, 'Approval cannot mark onsite payment collected');
assert.deepEqual(paymentCollections(onsite, 350), []);
const onsiteNoShow = { ...onsite, status: 'cancelled', cancelledBy: 'no-show' };
assert.equal(report(onsiteNoShow).totals.revenue, 0, 'Onsite no-show has no collection');
for (const confirmation of [{}, { cashCollected: true, cashAmount: 250 }]) assert.throws(() => paymentUpdate(onsite, 'completed', cashDate, confirmation), { status: 400 });
const onsiteCompleted = { ...onsite, ...paymentUpdate(onsite, 'completed', cashDate, { cashCollected: true, cashAmount: 350 }) };
assert.equal(onsiteCompleted.bookingFeePaid, true);
assert.equal(onsiteCompleted.servicePaid, true);
assert.equal(report(onsiteCompleted).totals.revenue, 350);
assert.equal(report(onsiteCompleted).collections.records.length, 1);
assert.deepEqual(report(onsiteCompleted).collections.records.map(item => [item.component, item.tender, item.amount]), [['booking-total', 'cash', 350]]);
const online = { ...pending, servicePaymentMethod: 'online' };
assert.equal(report({ ...online, ...paymentUpdate(online, 'confirmed', feeDate) }).totals.revenue, 350);
assert.deepEqual(paymentUpdate({ ...online, demoPayment: true }, 'confirmed'), {});
assert.equal(report({ ...completed, demoPayment: true }).totals.revenue, 0);
assert.equal(report({ total: 350, paid: true, createdAt: feeDate }).totals.revenue, 350, 'Legacy online receipts remain compatible');
assert.equal(report({ ...pending, bookingFee: 0, ...paymentUpdate(pending, 'confirmed', feeDate) }).totals.revenue, 0);
console.log('Split payment verification, cash collection, timestamps, revenue, demos and legacy compatibility passed');

async function testQueueSettlement() {
  const { ObjectId } = require('mongodb');
  const { memoryDb } = require('./helpers/memory-db');
  const frontDesk = require('../lib/front-desk')({ withAppointmentMutation: async (db, id, work) => work(), notify: async () => {}, serviceDuration: () => 30 });
  for (const status of ['done', 'cancelled']) {
    const appointment = { ...approved, _id: new ObjectId(), status: 'confirmed', partyMembers: ['Customer'], arrivals: { 0: feeDate } };
    const ticket = { _id: new ObjectId(), appointmentId: String(appointment._id), source: 'appointment', status, ...(status === 'done' ? confirmation : {}) };
    const db = memoryDb({ appointments: [appointment], queue: [ticket], appointmentSlots: [] });
    await frontDesk.complete(db, ticket, status);
    const settled = await db.collection('appointments').findOne({ _id: appointment._id });
    assert.equal(settled.status, status === 'done' ? 'completed' : 'cancelled');
    assert.equal(report(settled).totals.revenue, status === 'done' ? 350 : 100);
    await frontDesk.complete(db, ticket, status);
    assert.equal(report(await db.collection('appointments').findOne({ _id: appointment._id })).totals.revenue, status === 'done' ? 350 : 100);
  }
  console.log('Queue settlement collects cash once; cancellation never collects service balance (in-memory, no SMS)');
}
testQueueSettlement().catch(error => { console.error(error); process.exitCode = 1; });
