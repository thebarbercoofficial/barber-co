const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { Readable } = require('node:stream');
const { ObjectId } = require('mongodb');
const jwt = require('jsonwebtoken');
const { memoryDb } = require('./helpers/memory-db');
const security = require('../lib/account-security');
const localRequire = require('node:module').createRequire(path.resolve('api/index.js'));
const secret = 'isolated-contact-test';
const users = ['admin', 'moderator', 'customer'].map((role) => ({ _id: new ObjectId(), email: `${role}@review.test`, role }));
const database = memoryDb({ users });
let ready = false;
let reject = false;
const sent = [];
const context = { require: (name) => name === '../lib/account-security' ? { ...security, emailReady: () => ready, sendEmail: async (...args) => { if (reject) throw new Error('Provider unavailable'); sent.push(args); } } : localRequire(name), module: { exports: {} }, process: { env: { JWT_SECRET: secret, ADMIN_EMAIL: 'shop@example.com' } }, URL, console, fixtureDatabase: database };
vm.runInNewContext(`${fs.readFileSync('api/index.js', 'utf8')}\ndb = async () => fixtureDatabase;`, context);
const tokens = Object.fromEntries(users.map((user) => [user.role, jwt.sign({ sub: String(user._id) }, secret)]));
const token = (role) => tokens[role];

async function request({ body = {}, method = 'POST', path: pathname = '/api/contact', role } = {}) {
  const req = Readable.from([JSON.stringify(body)]);
  Object.assign(req, { method, url: pathname, headers: role ? { authorization: `Bearer ${token(role)}` } : {} });
  let result;
  const res = { statusCode: 0, setHeader() {}, end(data) { result = JSON.parse(data); } };
  await context.module.exports(req, res);
  return { status: res.statusCode, ...result };
}

async function main() {
  const body = { name: 'QA Test', email: 'qa@example.com', message: 'Isolated enquiry, no real email is sent.' };
  assert.equal((await request({ body: { ...body, email: 'invalid' } })).status, 400);
  const initial = await request({ body });
  assert.equal(initial.status, 201, 'Messages should still reach the staff inbox without configured email');
  assert.match(initial.message, /saved to the staff inbox/i);
  assert.equal(sent.length, 0);
  assert.equal((await request({ body: { ...body, email: 'qa@example.com' } })).status, 429);
  assert.equal((await request({ method: 'GET', path: '/api/admin/contacts' })).status, 401);
  assert.equal((await request({ method: 'GET', path: '/api/admin/contacts', role: 'customer' })).status, 403);
  let inbox = await request({ method: 'GET', path: '/api/admin/contacts', role: 'moderator' });
  assert.equal(inbox.status, 200);
  assert.equal(inbox.contacts.length, 1);
  assert.equal(inbox.contacts[0].email, body.email);
  assert.equal((await request({ method: 'GET', path: '/api/admin/contacts', role: 'admin' })).contacts.length, 1);

  ready = true;
  const second = { ...body, email: 'other@example.com' };
  assert.equal((await request({ body: second })).status, 201);
  assert.equal(sent[0][0], 'shop@example.com');
  assert.match(sent[0][2], /Reply to: other@example.com/);
  reject = true;
  const third = { ...body, email: 'third@example.com' };
  const savedDespiteEmailFailure = await request({ body: third });
  assert.equal(savedDespiteEmailFailure.status, 201);
  assert.match(savedDespiteEmailFailure.message, /email alert is unavailable/i);
  inbox = await request({ method: 'GET', path: '/api/admin/contacts', role: 'admin' });
  assert.equal(inbox.contacts.length, 3, 'The staff inbox must retain messages if email delivery fails');
  const replyPath = `/api/admin/contacts/${inbox.contacts[0]._id}/reply`;
  const reply = { message: 'Thanks for your enquiry. We can help at the shop.', requestId: '11111111-1111-4111-8111-111111111111' };
  assert.equal((await request({ path: replyPath, body: reply })).status, 401);
  for (const role of ['customer', 'moderator']) assert.equal((await request({ path: replyPath, body: reply, role })).status, 403);
  assert.equal((await request({ path: replyPath, body: { ...reply, message: '' }, role: 'admin' })).status, 400);
  assert.equal((await request({ path: replyPath, body: reply, role: 'admin' })).status, 503);
  reject = false;
  const accepted = await request({ path: replyPath, body: reply, role: 'admin' });
  assert.equal(accepted.status, 200);
  const deliveries = sent.length;
  assert.equal((await request({ path: replyPath, body: reply, role: 'admin' })).status, 200);
  assert.equal(sent.length, deliveries, 'Repeated send must not duplicate an accepted reply');
  assert.equal(sent.at(-1)[0], inbox.contacts[0].email);
  inbox = await request({ method: 'GET', path: '/api/admin/contacts', role: 'admin' });
  assert.equal(inbox.contacts[0].replies[0].status, 'accepted');
  assert.equal(inbox.contacts[0].status, 'replied');
  const customer = users.find((item) => item.role === 'customer');
  const firstService = { _id: new ObjectId(), slug: 'first-cut', name: 'First cut', active: true };
  const secondService = { _id: new ObjectId(), slug: 'second-cut', name: 'Second cut', active: true };
  database.records.services = [firstService, secondService];
  const servicePath = `/api/admin/services/${firstService._id}`;
  assert.equal((await request({ method: 'DELETE', path: servicePath, role: 'customer' })).status, 403);
  assert.equal((await request({ method: 'DELETE', path: servicePath, role: 'admin' })).status, 200);
  assert.equal((await request({ method: 'GET', path: '/api/admin/services', role: 'admin' })).services.length, 1);
  assert.equal((await request({ method: 'GET', path: '/api/catalog' })).services.length, 1);
  assert.equal(database.records.services.length, 2, 'Removing a service preserves its historical record');
  assert.equal((await request({ method: 'DELETE', path: servicePath, role: 'admin' })).status, 404);
  assert.equal((await request({ method: 'DELETE', path: `/api/admin/services/${secondService._id}`, role: 'admin' })).status, 409);
  const restored = await request({ path: '/api/admin/services', role: 'admin', body: { name: 'First cut', price: 150, duration: '30 min' } });
  assert.equal(restored.status, 201);
  assert.equal(database.records.services.length, 2, 'Re-adding restores the service without duplicating history');
  assert.equal(firstService.active, true);
  assert.equal(firstService.price, 150);
  assert.equal((await request({ path: '/api/admin/services', role: 'admin', body: { name: 'FIRST CUT', price: 200 } })).status, 409);
  assert.equal((await request({ path: '/api/admin/services', role: 'admin', body: { name: '', price: 150 } })).status, 400);
  const accessPath = `/api/admin/users/${customer._id}`;
  for (const role of ['customer', 'moderator']) assert.equal((await request({ method: 'PATCH', path: accessPath, role, body: { adminTestAccess: true } })).status, 403);
  assert.equal((await request({ method: 'PATCH', path: accessPath, role: 'admin', body: { adminTestAccess: true } })).status, 200);
  assert.equal(customer.adminTestAccess, true);
  assert.equal(customer.phoneVerifiedAt, undefined, 'Test access must not falsely verify a number');
  assert.equal((await request({ method: 'PATCH', path: accessPath, role: 'admin', body: { adminTestAccess: false } })).status, 200);
  assert.equal(customer.adminTestAccess, false);
  const booking = { _id: new ObjectId(), userId: customer._id, status: 'confirmed', date: '2099-11-03', time: '13:00', serviceId: 'cut', barberId: '', paid: true, total: 250 };
  database.records.appointments = [booking];
  database.records.settings = [{ _id: 'shop' }];
  const customerPath = `/api/appointments/${booking._id}`;
  assert.equal((await request({ method: 'PATCH', path: `${customerPath}/cancel`, body: { acceptNoRefund: true } })).status, 401);
  assert.equal((await request({ method: 'PATCH', path: `${customerPath}/cancel`, role: 'moderator', body: { acceptNoRefund: true } })).status, 404);
  assert.equal((await request({ method: 'PATCH', path: `${customerPath}/cancel`, role: 'customer' })).status, 400);
  assert.equal((await request({ method: 'PATCH', path: `${customerPath}/reschedule`, role: 'moderator', body: { date: '2099-11-04', time: '14:00' } })).status, 404);
  assert.equal((await request({ method: 'PATCH', path: `${customerPath}/reschedule`, role: 'customer', body: { date: '2000-01-01', time: '14:00' } })).status, 400);
  const moved = await request({ method: 'PATCH', path: `${customerPath}/reschedule`, role: 'customer', body: { date: '2099-11-04', time: '14:00' } });
  assert.equal(moved.status, 200, JSON.stringify(moved));
  assert.equal(booking.date, '2099-11-04');
  assert.equal((await request({ method: 'PATCH', path: `${customerPath}/cancel`, role: 'customer', body: { acceptNoRefund: true } })).status, 200);
  assert.equal(booking.status, 'cancelled');
  assert.equal(booking.paid, true, 'Cancellation must preserve collected-payment history');
  assert.equal(booking.noRefund, true);
  assert.equal((await request({ method: 'PATCH', path: `${customerPath}/reschedule`, role: 'customer', body: { date: '2099-11-05', time: '14:00' } })).status, 409);
  const deletePath = `/api/admin/users/${customer._id}`;
  assert.equal((await request({ method: 'DELETE', path: deletePath, role: 'moderator' })).status, 403);
  assert.equal((await request({ method: 'DELETE', path: deletePath, role: 'customer' })).status, 403);
  assert.equal((await request({ method: 'DELETE', path: deletePath, role: 'admin', body: { confirmEmail: 'wrong' } })).status, 400);
  const admin = users.find((item) => item.role === 'admin');
  assert.equal((await request({ method: 'DELETE', path: `/api/admin/users/${admin._id}`, role: 'admin', body: { confirmEmail: admin.email } })).status, 403);
  const otherAdmin = { _id: new ObjectId(), role: 'admin', email: 'other-admin@review.test' };
  database.records.users.push(otherAdmin);
  assert.equal((await request({ method: 'DELETE', path: `/api/admin/users/${otherAdmin._id}`, role: 'admin', body: { confirmEmail: otherAdmin.email } })).status, 403);
  database.records.appointments = [{ _id: new ObjectId(), userId: customer._id, paid: true }];
  assert.equal((await request({ method: 'DELETE', path: deletePath, role: 'admin', body: { confirmEmail: customer.email } })).status, 200);
  assert.equal(await database.collection('users').findOne({ _id: customer._id }), null);
  assert.equal(database.records.appointments.length, 1, 'Deleting an account preserves historical payments/bookings');
  assert.equal((await request({ method: 'GET', path: '/api/me', role: 'customer' })).status, 401);
  console.log('Contact API: validation, persistence, email fallback, rate limits, and staff-only inbox access passed.');
}

main().catch((error) => { console.error(error); process.exitCode = 1; });
