const assert = require('node:assert/strict');
const { ObjectId } = require('mongodb');
const { memoryDb } = require('./helpers/memory-db');
const notices = [];
const desk = require('../lib/front-desk')({ withAppointmentMutation: async (db, id, fn) => fn(), notify: async (...args) => notices.push(args[2]), serviceDuration: () => 30 });
const now = new Date('2100-03-03T06:00:00Z');
const barber = { _id: new ObjectId(), slug: 'alex', status: 'active' };
const other = { _id: new ObjectId(), slug: 'ben', status: 'active' };
const reservation = overrides => ({ _id: new ObjectId(), date: '2100-03-03', time: '14:00', status: 'confirmed', barberId: 'alex', customer: 'Ada', partySize: 1, partyMembers: ['Ada'], unitDurationMinutes: 30, durationMinutes: 30, total: 250, paid: true, paidAt: now, queueNumber: 4, graceDeadline: new Date(now.getTime() + 600000), ...overrides });
async function main() {
  const absent = reservation();
  const present = reservation({ barberId: 'ben', partySize: 2, partyMembers: ['Ben', 'Cal'], durationMinutes: 60 });
  const db = memoryDb({ appointments: [absent, present], settings: [{ _id: 'shop', gracePeriodMinutes: 10 }], barbers: [barber, other], queue: [], appointmentSlots: [{ _id: '2100-03-03:alex:840', appointmentId: String(absent._id) }, { _id: '2100-03-03:ben:840', appointmentId: String(present._id) }, { _id: '2100-03-03:ben:870', appointmentId: String(present._id) }] });
  await desk.checkIn(db, String(present._id), [0], now);
  await desk.checkIn(db, String(present._id), [0], now);
  assert.equal(db.records.queue.length, 1, 'repeated check-in creates no duplicate');
  assert.equal(db.records.queue[0].price, 0, 'booking payment is not counted again');
  await desk.sweep(db, new Date(now.getTime() + 660000));
  const missed = db.records.appointments.find(item => String(item._id) === String(absent._id));
  const checked = db.records.appointments.find(item => String(item._id) === String(present._id));
  assert.equal(missed.cancelledBy, 'no-show');
  assert.equal(missed.paid, true);
  assert.equal(missed.total, 250);
  assert.equal(missed.noRefund, true);
  assert.equal(checked.status, 'confirmed', 'barber delay does not cancel present members');
  assert.deepEqual(checked.absentMembers.map(item => item.name), ['Cal']);
  assert.equal(checked.reservedDurationMinutes, 30);
  assert.equal(db.records.appointmentSlots.length, 1, 'unused member slots released');
  await assert.rejects(desk.checkIn(db, String(absent._id), [0], new Date(now.getTime() + 660000)), /approved/);
  const selection = await desk.selectService(db, '', new Date(now.getTime() + 660000));
  assert.equal(selection.ticket.customer, 'Ben');
  db.records.queue[0].status = 'done';
  await desk.complete(db, db.records.queue[0], 'done');
  assert.equal(db.records.appointments.find(item => String(item._id) === String(present._id)).status, 'completed');
  assert.equal(db.records.appointmentSlots.length, 0);
  assert.equal(notices.length, 2);
  await desk.sweep(db, new Date(now.getTime() + 720000));
  assert.equal(notices.length, 2, 'no repeated forfeiture notifications');

  const upcoming = reservation({ time: '14:30', graceDeadline: new Date('2100-03-03T06:40:00Z') });
  const walkin = { _id: new ObjectId(), status: 'waiting', customer: 'Walk-in', queueNumber: 1, serviceId: 'cut', durationMinutes: 30, barberId: 'alex' };
  const capacity = memoryDb({ appointments: [upcoming], barbers: [barber, other], queue: [walkin], services: [] });
  assert.equal(await desk.selectService(capacity, '', new Date('2100-03-03T06:10:00Z')), null, 'walk-in cannot overrun reservation');
  walkin.barberId = 'ben';
  assert.equal((await desk.selectService(capacity, '', new Date('2100-03-03T06:10:00Z'))).barberId, 'ben', 'other barbers remain available');
  walkin.barberId = 'alex';
  assert.ok(await desk.selectService(capacity, '', now), 'exactly fitting walk-in may start');
  capacity.records.queue.push({ _id: new ObjectId(), status: 'serving', barberId: 'alex' });
  await assert.rejects(desk.selectService(capacity, String(walkin._id), now), /busy/);
  const legacy = reservation({ time: '13:00', graceDeadline: undefined });
  capacity.records.appointments.push(legacy);
  await desk.sweep(capacity, now);
  assert.equal(legacy.status, 'confirmed', 'do not retroactively cancel old reservations on rollout');
  const retryBooking = reservation({ graceDeadline: now });
  const retryDb = memoryDb({ appointments: [retryBooking], appointmentSlots: [{ _id: '2100-03-03:alex:840', appointmentId: String(retryBooking._id) }] });
  const collection = retryDb.collection.bind(retryDb);
  let failDelete = true;
  retryDb.collection = name => {
    const result = collection(name);
    if (name === 'appointmentSlots' && failDelete) result.deleteOne = async () => { failDelete = false; throw new Error('Database interruption'); };
    return result;
  };
  await assert.rejects(desk.sweep(retryDb, now), /interruption/);
  assert.equal(retryBooking.status, 'cancelled');
  await desk.sweep(retryDb, now);
  assert.equal(retryDb.records.appointmentSlots.length, 0, 'retry releases slots after a failed database deletion');
  console.log('Front desk: idempotent member check-in, no-show forfeiture, partial attendance, delayed barber protection, slot release and walk-in capacity passed');
}
main().catch(error => { console.error(error); process.exitCode = 1; });
