const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const { Readable } = require('node:stream');
const { ObjectId } = require('mongodb');
const jwt = require('jsonwebtoken');
const { memoryDb } = require('./helpers/memory-db');
const localRequire = require('node:module').createRequire(path.resolve('api/index.js'));
const users = ['customer', 'moderator', 'customer'].map((role, i) => ({ _id: new ObjectId(), role, name: `Person ${i}`, email: `${i}@test.invalid` }));
const barber = { _id: new ObjectId(), slug: 'test-barber', status: 'active' };
const service = { _id: new ObjectId(), slug: 'basic', duration: '1 hour', price: 150 };
const database = memoryDb({ users, appointmentSlots: [], barbers: [barber], services: [service], settings: [{ _id: 'shop', bookingFee: 100, paymentMode: 'live', gcash: { enabled: true, accountNumber: '09123456789' } }] });
const notices = [];
const context = { require: name => name === '../lib/notifications' ? { notify: async (...args) => notices.push(args[2]) } : name === '../lib/receipt' ? { validateReceipt: async () => {} } : localRequire(name), module: { exports: {} }, process: { env: { JWT_SECRET: 'test', ALLOW_UNVERIFIED_ACCOUNTS: 'true' } }, URL, console, database };
vm.runInNewContext(`${fs.readFileSync('api/index.js', 'utf8')}\ndb = async () => database; module.exports.test = { cleanLegacyCapacity, serviceDuration };`, context);
const api = context.module.exports;
async function request(url, body, user = 0, method = 'POST') {
  const req = Readable.from(body ? [JSON.stringify(body)] : []);
  Object.assign(req, { method, url: `/api${url}`, headers: { authorization: `Bearer ${jwt.sign({ sub: String(users[user]._id) }, 'test')}` } });
  let result;
  const res = { setHeader() {}, end(data) { result = JSON.parse(data); } };
  await api(req, res);
  return { status: res.statusCode, ...result };
}
const group = { serviceId: 'basic', barberId: barber.slug, date: '2100-03-03', time: '14:00', partySize: 3, partyMembers: ['Ada', 'Ben', 'Cal'] };
const payment = { nonRefundableAccepted: true, paymentMethod: 'GCash', paymentProof: 'data:image/png;base64,dGVzdA==' };
async function main() {
  assert.equal(api.test.serviceDuration('1 hour'), 60);
  assert.equal(api.test.serviceDuration('1 hour 30 min'), 90);
  for (const invalid of [{ partySize: 0 }, { partySize: 11 }, { partySize: 1.5 }, { partySize: '3' }, { partyMembers: ['Ada'] }, { partyMembers: ['Ada', '', 'Cal'] }]) {
    assert.equal((await request('/appointment-holds', { ...group, ...invalid })).status, 400);
    assert.equal((await request('/appointments', { ...group, ...payment, ...invalid })).status, 400);
  }
  assert.equal((await request('/appointment-holds', { ...group, time: '18:00' })).status, 400);
  assert.equal((await request('/appointments', { ...group, ...payment, time: '18:00' })).status, 400);
  const hold = await request('/appointment-holds', group);
  assert.equal(hold.status, 201, JSON.stringify(hold));
  assert.equal(hold.hold.total, 550);
  assert.equal(hold.hold.durationMinutes, 180);
  assert.equal(hold.hold.unitDurationMinutes, 60);
  assert.equal(hold.hold.unitPrice, 150);
  assert.deepEqual(hold.hold.partyMembers, group.partyMembers);
  assert.equal((await request('/appointment-holds', group, 2)).status, 201);
  assert.equal((database.records.appointmentSlots || []).length, 0);
  const a = await request('/appointments', { ...group, ...payment, holdId: hold.hold.id });
  assert.equal(a.status, 201, JSON.stringify(a));
  const b = await request('/appointments', { ...group, ...payment }, 2);
  assert.equal(b.status, 201);
  assert.equal(database.records.appointmentSlots.length, 0);
  assert.deepEqual((await request('/availability?date=2100-03-03&time=14:00&serviceId=basic&partySize=3', null, 0, 'GET')).unavailableBarberIds, []);
  const approvals = await Promise.all([a, b].map(item => request(`/admin/appointments/${item.appointment.id}`, { status: 'confirmed' }, 1, 'PATCH')));
  assert.deepEqual(approvals.map(item => item.status).sort(), [200, 409]);
  const winner = database.records.appointments.find(item => item.status === 'confirmed');
  const loser = database.records.appointments.find(item => item.status === 'pending');
  assert.equal(winner.paid, true);
  assert.equal(loser.paid, false);
  assert.equal(database.records.appointmentSlots.length, 12);
  assert.ok(notices.some(text => text.includes('Ada, Ben, Cal')));
  service.duration = '30 min';
  assert.equal((await request(`/admin/appointments/${winner._id}/reschedule`, { date: '2100-03-04', time: '18:00' }, 1, 'PATCH')).status, 400);
  assert.equal((await request(`/admin/appointments/${winner._id}/reschedule`, { date: '2100-03-04', time: '14:00' }, 1, 'PATCH')).status, 200);
  assert.equal(database.records.appointmentSlots.length, 12);
  assert.ok(database.records.appointmentSlots.every(slot => slot._id.startsWith('2100-03-04:')));
  const target = { date: '2100-03-05', time: '14:00' };
  const proposed = await request(`/appointments/${loser._id}/reschedule`, target, 2, 'PATCH');
  assert.equal(proposed.status, 200);
  assert.equal((await request(`/admin/appointments/${loser._id}/reschedule-review`, { decision: 'approve', requestedAt: proposed.appointment.rescheduleRequest.requestedAt }, 1, 'PATCH')).status, 200);
  assert.equal(database.records.appointmentSlots.length, 12);
  database.records.appointmentSlots.push({ _id: 'legacy-pending', appointmentId: String(loser._id) });
  const legacyHold = { _id: new ObjectId() };
  database.records.appointmentHolds.push(legacyHold);
  database.records.appointmentSlots.push({ _id: 'legacy-hold', appointmentId: String(legacyHold._id) });
  await api.test.cleanLegacyCapacity(database);
  assert.equal(database.records.appointmentSlots.length, 12);
  const single = await request('/appointment-holds', { serviceId: 'basic', date: '2100-03-06', time: '14:00' });
  assert.equal(single.status, 201);
  assert.deepEqual(single.hold.partyMembers, [users[0].name]);
  const approveLoser = () => request(`/admin/appointments/${loser._id}`, { status: 'confirmed' }, 1, 'PATCH');
  loser.time = '18:00';
  assert.equal((await approveLoser()).status, 409);
  loser.time = '14:00';
  service.active = false;
  assert.equal((await approveLoser()).status, 409);
  service.active = true;
  loser.date = '2020-03-03';
  assert.equal((await approveLoser()).status, 409);
  assert.equal(loser.paid, false);
  assert.equal(database.records.appointmentSlots.length, 12);
  console.log('Group quotes, validation, overlap, atomic approvals, snapshots, reschedules and legacy cleanup passed');
}
main().catch(error => { console.error(error); process.exitCode = 1; });
