const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const { Readable } = require('node:stream');
const { ObjectId } = require('mongodb');
const jwt = require('jsonwebtoken');
const { memoryDb } = require('./helpers/memory-db');
const localRequire = require('node:module').createRequire(path.resolve('api/index.js'));
const users = ['customer', 'moderator', 'customer'].map(role => ({ _id: new ObjectId(), role }));
const barber = { _id: new ObjectId(), slug: 'test-barber', status: 'active' };
const database = memoryDb({ users, settings: [{ _id: 'shop' }], barbers: [barber], services: [{ _id: new ObjectId(), slug: 'basic', duration: '30 min' }] });
const notices = new Set();
let failNotify = false;
const context = { require: name => name === '../lib/notifications' ? { notify: async (db, user, text, key) => { if (failNotify) throw new Error('offline'); notices.add(key); } } : localRequire(name), module: { exports: {} }, process: { env: { JWT_SECRET: 'test', ALLOW_UNVERIFIED_ACCOUNTS: 'true' } }, URL, console, database };
vm.runInNewContext(`${fs.readFileSync('api/index.js', 'utf8')}\ndb = async () => database; module.exports.test = { withAppointmentMutation, rescheduleDeadline };`, context);
const api = context.module.exports;
async function request(url, body, user = 0, method = 'PATCH') {
  const req = Readable.from(body ? [JSON.stringify(body)] : []);
  Object.assign(req, { method, url: `/api${url}`, headers: { authorization: `Bearer ${jwt.sign({ sub: String(users[user]._id) }, 'test')}` } });
  let result;
  const res = { setHeader() {}, end(data) { result = JSON.parse(data); } };
  await api(req, res);
  return { status: res.statusCode, ...result };
}
function fixture() {
  const appointment = { _id: new ObjectId(), userId: users[0]._id, barberId: barber.slug, serviceId: 'basic', date: '2100-03-03', time: '14:00', status: 'confirmed', paid: true, paidAt: new Date('2026-01-01'), total: 250, paymentProof: 'unchanged' };
  database.records.appointments = [appointment];
  database.records.appointmentSlots = [780, 795].map(minute => ({ _id: `2100-03-03:${barber._id}:${minute + 60}`, appointmentId: String(appointment._id) }));
  return appointment;
}
async function main() {
  let current = fixture();
  const endpoint = () => `/appointments/${current._id}/reschedule`;
  const review = () => `/admin/appointments/${current._id}/reschedule-review`;
  const target = { date: '2100-03-04', time: '15:00' };
  assert.equal((await request('/appointments', {}, 0, 'POST')).status, 400);
  assert.equal((await request(endpoint(), target, 2)).status, 404);
  assert.equal((await request(endpoint(), { ...target, time: '23:00' })).status, 400);
  let result = await request(endpoint(), target);
  assert.equal(result.status, 200, JSON.stringify(result));
  assert.equal(current.date, '2100-03-03');
  assert.equal(current.rescheduleRequest.originalTime, '14:00');
  assert.equal(current.rescheduleRequest.expiresAt.toISOString(), '2100-03-03T06:00:00.000Z');
  assert.equal(database.records.appointmentSlots.length, 2);
  assert.equal((await request(endpoint(), target)).status, 409);
  assert.equal((await request(`/admin/appointments/${current._id}`, { status: 'completed' }, 1)).status, 409);
  assert.equal((await request(review(), { decision: 'approve' }, 0)).status, 403);
  assert.equal((await request(review(), { decision: 'approve', requestedAt: 'stale' }, 1)).status, 409);
  let version = result.appointment.rescheduleRequest.requestedAt;
  assert.equal((await request(review(), { decision: 'reject', requestedAt: version, reason: 'Unavailable' }, 1)).status, 200);
  assert.equal(current.date, '2100-03-03');
  assert.equal(current.rescheduleRequest.status, 'rejected');
  result = await request(endpoint(), target);
  version = result.appointment.rescheduleRequest.requestedAt;
  const conflictingSlot = { _id: `2100-03-04:${barber._id}:900`, appointmentId: 'competitor' };
  database.records.appointmentSlots.push(conflictingSlot);
  assert.equal((await request(review(), { decision: 'approve', requestedAt: version }, 1)).status, 409);
  assert.equal(current.time, '14:00');
  assert.equal(database.records.appointmentSlots.filter(slot => slot.appointmentId === String(current._id)).length, 2);
  database.records.appointmentSlots = database.records.appointmentSlots.filter(slot => slot !== conflictingSlot);
  assert.equal((await request(review(), { decision: 'approve', requestedAt: version }, 1)).status, 200);
  assert.equal(current.date, target.date);
  assert.equal(current.rescheduleRequest.status, 'approved');
  assert.equal(current.paid, true);
  assert.equal(current.paymentProof, 'unchanged');
  assert.ok(database.records.appointmentSlots.every(slot => slot._id.startsWith(target.date) && slot.appointmentId === String(current._id)));
  assert.equal((await request(review(), { decision: 'approve', requestedAt: version }, 1)).status, 409);
  current = fixture();
  assert.equal((await request(`/admin/appointments/${current._id}/reschedule`, target, 1)).status, 200);
  assert.equal(current.date, target.date);
  for (const proposed of [{ date: '2100-03-02', time: '15:00' }, target]) {
    current = fixture();
    result = await request(endpoint(), proposed);
    const deadline = new Date(result.appointment.rescheduleRequest.expiresAt);
    await api.sweepRescheduleRequests(database, new Date(deadline.getTime() - 1));
    assert.equal(current.status, 'confirmed');
    failNotify = true;
    await assert.rejects(api.sweepRescheduleRequests(database, deadline), /offline/);
    assert.equal(current.status, 'cancelled');
    failNotify = false;
    await api.sweepRescheduleRequests(database, deadline);
    assert.equal(current.rescheduleRequest.status, 'expired');
    assert.equal(current.paid, true);
    assert.equal(current.noRefund, true);
    assert.equal(database.records.appointmentSlots.length, 0);
    const count = notices.size;
    await api.sweepRescheduleRequests(database, deadline);
    assert.equal(notices.size, count);
  }
  current = fixture();
  await request(endpoint(), target);
  current.rescheduleRequest.date = '2020-03-03';
  assert.equal((await request('/appointments/mine', null, 0, 'GET')).status, 200);
  assert.equal(current.status, 'cancelled');
  current = fixture();
  let release;
  const held = api.test.withAppointmentMutation(database, String(current._id), () => new Promise(resolve => { release = resolve; }));
  await new Promise(resolve => setImmediate(resolve));
  assert.equal((await request(`/admin/appointments/${current._id}`, { status: 'completed' }, 1)).status, 409);
  assert.equal((await request(`/appointments/${current._id}/cancel`, { acceptNoRefund: true })).status, 409);
  release();
  await held;
  assert.equal((await request(`/admin/appointments/${current._id}`, { status: 'completed' }, 1)).status, 200);
  console.log('Reschedule request, review versions, capacity locks, expiration retries, read catch-up, payment preservation and mutation leases passed');
}
main().catch(error => { console.error(error); process.exitCode = 1; });
