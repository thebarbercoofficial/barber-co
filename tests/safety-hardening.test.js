async function request(route, body, actor = user, method = 'POST') {
  const req = Readable.from(body ? [JSON.stringify(body)] : []);
  Object.assign(req, { url: `/api${route}`, method, headers: actor ? { authorization: `Bearer ${jwt.sign({ sub: String(actor._id) }, 'isolated-safety-test')}` } : {} });
  let data;
  const res = { setHeader() {}, end(raw) { data = JSON.parse(raw); } };
  await context.module.exports(req, res);
  return { status: res.statusCode, ...data };
}
async function main() {
  const validation = { holdId: String(hold._id), paymentRevision: context.module.exports.settings(settings).paymentRevision };
  assert.equal((await request('/checkout/validate', validation)).status, 200);
  assert.equal((await request('/checkout/validate', validation, admin)).status, 409, 'Checkout belongs to its customer');
  assert.equal((await request('/checkout/validate', { ...validation, paymentRevision: 'old' })).status, 409);
  database.records.services[0].price = 200;
  assert.equal((await request('/checkout/validate', validation)).status, 409, 'Repricing blocks old checkout');
  database.records.services[0].price = 150;
  hold.expiresAt = new Date(0);
  assert.equal((await request('/checkout/validate', validation)).status, 409);
  assert.equal((await request(`/admin/barbers/${barber._id}`, {}, admin, 'DELETE')).status, 409);
  assert.equal((await request(`/admin/barbers/${barber._id}`, { status: 'on-leave' }, admin, 'PATCH')).status, 409);
  assert.equal(barber.status, 'active');
  booking.status = 'cancelled';
  assert.equal((await request(`/admin/barbers/${barber._id}`, {}, admin, 'DELETE')).status, 200);
  const proof = `data:image/png;base64,${(await require('sharp')({ create: { width: 10, height: 10, channels: 3, background: 'white' } }).png().toBuffer()).toString('base64')}`;
  const recovery = { reference: 'wallet-1234', paymentProof: proof, date: hold.date, time: hold.time };
  assert.equal((await request('/payments/recovery', recovery, null)).status, 401);
  const first = await request('/payments/recovery', recovery);
  assert.equal(first.status, 201);
  assert.equal((await request('/payments/recovery', recovery)).reference, first.reference);
  assert.equal(database.records.contactMessages.length, 1, 'Retry must not duplicate recovery');
  assert.equal(database.records.appointments.length, 1, 'Recovery does not create a booking');
  assert.equal((await request(`/admin/contacts/${first.reference}/payment-proof`, null, user, 'GET')).status, 403);
  assert.equal((await request(`/admin/contacts/${first.reference}/payment-proof`, null, admin, 'GET')).paymentProof, proof);
  assert.equal((await request('/me', { smsConsent: false }, user, 'PATCH')).status, 200);
  assert.equal(user.smsConsent, false);
  booking.status = 'pending';
  await outbox.updateWithNotice(database, 'appointments', { _id: booking._id }, { $set: { status: 'confirmed' } });
  assert.equal(booking.status, 'confirmed');
  assert.equal(Object.values(booking.notificationOutbox).length, 1, 'Status and event persisted atomically');
  await assert.rejects(outbox.flush(database, async () => { throw new Error('crash'); }));
  assert.ok(booking.notificationOutbox, 'Failed dispatch leaves durable event');
  const events = [];
  await outbox.flush(database, async (...args) => events.push(args[3]));
  await outbox.flush(database, async (...args) => events.push(args[3]));
  assert.deepEqual(events, [`appointment:${booking._id}:confirmed`]);
  assert.equal(booking.notificationOutbox, undefined);
  console.log('Checkout ownership/expiry/repricing, recovery authorization/idempotency, barber commitments, SMS preferences, and durable crash-recovery events passed');
}
main().catch(error => { console.error(error); process.exitCode = 1; });
