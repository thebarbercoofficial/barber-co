const hold = { _id: new ObjectId(), userId: user._id, date: '2099-12-01', time: '14:00', serviceId: 'cut', barberId: 'alex', partySize: 1, partyMembers: ['Customer'], durationMinutes: 30, total: 250, expiresAt: new Date(Date.now() + 60000) };
const booking = { _id: new ObjectId(), userId: user._id, barberId: 'alex', status: 'confirmed', date: '2099-12-01', time: '14:00' };
const database = memoryDb({ users: [admin, user], barbers: [barber], settings: [settings], services: [{ _id: new ObjectId(), slug: 'cut', price: 150, duration: '30 min', active: true }], appointmentHolds: [hold], appointments: [booking] });
